export function escapeHtml(value: unknown) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
}

export function getSiteUrl() {
  return process.env.NEXT_PUBLIC_SITE_URL ?? 'https://klippa.co.za'
}
